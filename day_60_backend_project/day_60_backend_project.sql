BEGIN;

CREATE SCHEMA IF NOT EXISTS backend_api;

-- The application computes SHA-256 API-key digests. Plaintext credentials
-- are never stored in this schema.
CREATE TABLE IF NOT EXISTS backend_api.api_clients (
    client_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    key_hash VARCHAR(64) NOT NULL UNIQUE
        CHECK (key_hash ~ '^[0-9a-f]{64}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    requests_per_minute INTEGER NOT NULL DEFAULT 120
        CHECK (requests_per_minute BETWEEN 1 AND 100000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS backend_api.tasks (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL
        REFERENCES backend_api.api_clients(client_id),
    title VARCHAR(160) NOT NULL
        CHECK (length(trim(title)) BETWEEN 1 AND 160),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'in_progress',
            'completed',
            'cancelled'
        )),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_task_client_pair UNIQUE (task_id, client_id)
);

CREATE TABLE IF NOT EXISTS backend_api.idempotency_records (
    client_id BIGINT NOT NULL
        REFERENCES backend_api.api_clients(client_id),
    idempotency_key VARCHAR(128) NOT NULL
        CHECK (idempotency_key ~ '^[A-Za-z0-9._:-]{8,128}$'),
    request_hash VARCHAR(64) NOT NULL
        CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    task_id BIGINT,
    response_status SMALLINT NOT NULL DEFAULT 201
        CHECK (response_status BETWEEN 200 AND 299),
    response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (client_id, idempotency_key),
    CONSTRAINT fk_idempotency_task_client
        FOREIGN KEY (task_id, client_id)
        REFERENCES backend_api.tasks(task_id, client_id)
        ON DELETE CASCADE,
    CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS backend_api.request_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    client_id BIGINT
        REFERENCES backend_api.api_clients(client_id)
        ON DELETE SET NULL,
    http_method VARCHAR(10) NOT NULL
        CHECK (http_method IN (
            'GET',
            'POST',
            'PATCH',
            'PUT',
            'DELETE',
            'OPTIONS'
        )),
    route TEXT NOT NULL,
    response_status SMALLINT NOT NULL
        CHECK (response_status BETWEEN 100 AND 599),
    duration_ms NUMERIC(12, 3)
        CHECK (duration_ms IS NULL OR duration_ms >= 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS backend_api.rate_limit_windows (
    client_id BIGINT NOT NULL
        REFERENCES backend_api.api_clients(client_id)
        ON DELETE CASCADE,
    window_start TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0
        CHECK (request_count >= 0),
    max_requests INTEGER NOT NULL
        CHECK (max_requests > 0),
    PRIMARY KEY (client_id, window_start)
);

CREATE INDEX IF NOT EXISTS idx_tasks_client_created
    ON backend_api.tasks(client_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_tasks_client_status_created
    ON backend_api.tasks(client_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_idempotency_expiry
    ON backend_api.idempotency_records(expires_at);

CREATE INDEX IF NOT EXISTS idx_request_audit_time
    ON backend_api.request_audit(occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_request_audit_client_time
    ON backend_api.request_audit(client_id, occurred_at DESC);

CREATE OR REPLACE FUNCTION backend_api.touch_task_version()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.title IS DISTINCT FROM OLD.title
       OR NEW.description IS DISTINCT FROM OLD.description
       OR NEW.status IS DISTINCT FROM OLD.status THEN
        NEW.version := OLD.version + 1;
        NEW.updated_at := clock_timestamp();
    ELSE
        NEW.version := OLD.version;
        NEW.updated_at := OLD.updated_at;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_task_version
    ON backend_api.tasks;

CREATE TRIGGER trg_touch_task_version
BEFORE UPDATE ON backend_api.tasks
FOR EACH ROW
EXECUTE FUNCTION backend_api.touch_task_version();

-- The client identifier is derived from a digest supplied by the application.
CREATE OR REPLACE FUNCTION backend_api.authenticate_client(
    p_key_hash VARCHAR
)
RETURNS BIGINT
LANGUAGE SQL
STABLE
AS $$
    SELECT client_id
    FROM backend_api.api_clients
    WHERE key_hash = p_key_hash
      AND is_active = TRUE
    LIMIT 1;
$$;

-- Idempotency is scoped to an API client. A unique key with a different
-- payload is rejected rather than silently returning an unrelated resource.
CREATE OR REPLACE FUNCTION backend_api.create_task(
    p_client_id BIGINT,
    p_idempotency_key VARCHAR,
    p_request_hash VARCHAR,
    p_title VARCHAR,
    p_description VARCHAR DEFAULT ''
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_record backend_api.idempotency_records%ROWTYPE;
    v_task_id BIGINT;
    v_response JSONB;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM backend_api.api_clients
        WHERE client_id = p_client_id
          AND is_active = TRUE
    ) THEN
        RAISE EXCEPTION 'API client is inactive or unavailable'
            USING ERRCODE = '42501';
    END IF;

    IF p_idempotency_key IS NULL
       OR p_idempotency_key !~ '^[A-Za-z0-9._:-]{8,128}$' THEN
        RAISE EXCEPTION 'Invalid idempotency key'
            USING ERRCODE = '22023';
    END IF;

    IF p_request_hash IS NULL
       OR p_request_hash !~ '^[0-9a-f]{64}$' THEN
        RAISE EXCEPTION 'Invalid request hash'
            USING ERRCODE = '22023';
    END IF;

    -- Remove only an expired record for the key being submitted.
    DELETE FROM backend_api.idempotency_records
    WHERE client_id = p_client_id
      AND idempotency_key = p_idempotency_key
      AND expires_at <= clock_timestamp();

    -- Concurrent inserts for the same client and key serialize through
    -- the primary-key conflict. The following SELECT reads the committed row.
    INSERT INTO backend_api.idempotency_records (
        client_id,
        idempotency_key,
        request_hash,
        expires_at
    )
    VALUES (
        p_client_id,
        p_idempotency_key,
        p_request_hash,
        clock_timestamp() + INTERVAL '24 hours'
    )
    ON CONFLICT (client_id, idempotency_key) DO NOTHING;

    SELECT *
    INTO v_record
    FROM backend_api.idempotency_records
    WHERE client_id = p_client_id
      AND idempotency_key = p_idempotency_key
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Idempotency record could not be established'
            USING ERRCODE = '40001';
    END IF;

    IF v_record.request_hash <> p_request_hash THEN
        RAISE EXCEPTION 'Idempotency key reused with a different payload'
            USING ERRCODE = '22023';
    END IF;

    IF v_record.task_id IS NOT NULL THEN
        RETURN v_record.task_id;
    END IF;

    INSERT INTO backend_api.tasks (
        client_id,
        title,
        description,
        status
    )
    VALUES (
        p_client_id,
        p_title,
        COALESCE(p_description, ''),
        'pending'
    )
    RETURNING task_id INTO v_task_id;

    SELECT jsonb_build_object(
        'id', task_id,
        'title', title,
        'description', description,
        'status', status,
        'version', version,
        'created_at', created_at,
        'updated_at', updated_at
    )
    INTO v_response
    FROM backend_api.tasks
    WHERE task_id = v_task_id;

    UPDATE backend_api.idempotency_records
    SET task_id = v_task_id,
        response_status = 201,
        response_body = v_response
    WHERE client_id = p_client_id
      AND idempotency_key = p_idempotency_key;

    RETURN v_task_id;
END;
$$;

-- Status changes are protected by a row lock and an expected version.
-- The trigger increments the version and timestamp after a real change.
CREATE OR REPLACE FUNCTION backend_api.transition_task_status(
    p_client_id BIGINT,
    p_task_id BIGINT,
    p_expected_version INTEGER,
    p_new_status VARCHAR
)
RETURNS TABLE (
    result_task_id BIGINT,
    result_status VARCHAR,
    result_version INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_task backend_api.tasks%ROWTYPE;
    v_transition_allowed BOOLEAN := FALSE;
BEGIN
    IF p_new_status NOT IN (
        'pending',
        'in_progress',
        'completed',
        'cancelled'
    ) THEN
        RAISE EXCEPTION 'Unsupported task status: %', p_new_status
            USING ERRCODE = '22023';
    END IF;

    SELECT *
    INTO v_task
    FROM backend_api.tasks
    WHERE task_id = p_task_id
      AND client_id = p_client_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Task is not available to this client'
            USING ERRCODE = 'P0002';
    END IF;

    IF v_task.version <> p_expected_version THEN
        RAISE EXCEPTION 'Task version conflict: expected %, actual %',
            p_expected_version,
            v_task.version
            USING ERRCODE = '40001';
    END IF;

    v_transition_allowed :=
        CASE v_task.status
            WHEN 'pending' THEN
                p_new_status IN ('in_progress', 'cancelled')
            WHEN 'in_progress' THEN
                p_new_status IN ('pending', 'completed', 'cancelled')
            ELSE FALSE
        END;

    IF p_new_status = v_task.status THEN
        v_transition_allowed := TRUE;
    END IF;

    IF NOT v_transition_allowed THEN
        RAISE EXCEPTION 'Invalid transition from % to %',
            v_task.status,
            p_new_status
            USING ERRCODE = '22023';
    END IF;

    UPDATE backend_api.tasks
    SET status = p_new_status
    WHERE task_id = p_task_id
      AND client_id = p_client_id;

    RETURN QUERY
    SELECT task_id, status, version
    FROM backend_api.tasks
    WHERE task_id = p_task_id
      AND client_id = p_client_id;
END;
$$;

-- Atomically increments a minute bucket only while its configured limit
-- has not been reached. The application supplies the window boundary.
CREATE OR REPLACE FUNCTION backend_api.consume_rate_limit(
    p_client_id BIGINT,
    p_window_start TIMESTAMPTZ
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
    v_max INTEGER;
BEGIN
    SELECT requests_per_minute
    INTO v_max
    FROM backend_api.api_clients
    WHERE client_id = p_client_id
      AND is_active = TRUE;

    IF NOT FOUND THEN
        RETURN FALSE;
    END IF;

    INSERT INTO backend_api.rate_limit_windows AS current_window (
        client_id,
        window_start,
        request_count,
        max_requests
    )
    VALUES (
        p_client_id,
        p_window_start,
        1,
        v_max
    )
    ON CONFLICT (client_id, window_start)
    DO UPDATE SET
        request_count = current_window.request_count + 1
    WHERE current_window.request_count < current_window.max_requests
    RETURNING request_count INTO v_count;

    RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION backend_api.evaluate_client_request(
    p_client_id BIGINT,
    p_window_start TIMESTAMPTZ
)
RETURNS TABLE (
    eligible BOOLEAN,
    reason TEXT
)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_client backend_api.api_clients%ROWTYPE;
    v_count INTEGER;
BEGIN
    SELECT *
    INTO v_client
    FROM backend_api.api_clients
    WHERE client_id = p_client_id;

    IF NOT FOUND THEN
        RETURN QUERY SELECT FALSE, 'client_not_found'::TEXT;
        RETURN;
    END IF;

    IF NOT v_client.is_active THEN
        RETURN QUERY SELECT FALSE, 'client_inactive'::TEXT;
        RETURN;
    END IF;

    SELECT COALESCE(request_count, 0)
    INTO v_count
    FROM backend_api.rate_limit_windows
    WHERE client_id = p_client_id
      AND window_start = p_window_start;

    IF v_count >= v_client.requests_per_minute THEN
        RETURN QUERY SELECT FALSE, 'rate_limit_reached'::TEXT;
        RETURN;
    END IF;

    RETURN QUERY SELECT TRUE, 'eligible'::TEXT;
END;
$$;

CREATE OR REPLACE VIEW backend_api.task_dashboard AS
SELECT
    client.client_id,
    client.client_name,
    client.is_active,
    COUNT(task.task_id) AS total_tasks,
    COUNT(task.task_id) FILTER (
        WHERE task.status = 'pending'
    ) AS pending_tasks,
    COUNT(task.task_id) FILTER (
        WHERE task.status = 'in_progress'
    ) AS in_progress_tasks,
    COUNT(task.task_id) FILTER (
        WHERE task.status = 'completed'
    ) AS completed_tasks,
    COUNT(task.task_id) FILTER (
        WHERE task.status = 'cancelled'
    ) AS cancelled_tasks,
    MAX(task.updated_at) AS last_task_update
FROM backend_api.api_clients AS client
LEFT JOIN backend_api.tasks AS task
    ON task.client_id = client.client_id
GROUP BY
    client.client_id,
    client.client_name,
    client.is_active;

CREATE OR REPLACE VIEW backend_api.request_error_report AS
SELECT
    client_id,
    http_method,
    route,
    response_status,
    COUNT(*) AS request_count,
    AVG(duration_ms) AS average_duration_ms,
    MAX(occurred_at) AS most_recent_occurrence
FROM backend_api.request_audit
WHERE response_status >= 400
GROUP BY
    client_id,
    http_method,
    route,
    response_status;

