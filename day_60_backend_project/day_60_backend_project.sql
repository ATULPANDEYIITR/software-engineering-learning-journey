-- Exercise optimistic-concurrency failure handling without aborting the
-- containing transaction.
DO $$
BEGIN
    PERFORM *
    FROM backend_api.transition_task_status(
        1001,
        50001,
        1,
        'completed'
    );

    RAISE EXCEPTION 'Expected an optimistic-concurrency failure.';
EXCEPTION
    WHEN SQLSTATE '40001' THEN
        RAISE NOTICE 'Expected result: stale version rejected.';
END;
$$;

-- A completed task cannot be moved back to pending.
DO $$
BEGIN
    PERFORM *
    FROM backend_api.transition_task_status(
        1001,
        50002,
        1,
        'pending'
    );

    RAISE EXCEPTION 'Expected an invalid-transition failure.';
EXCEPTION
    WHEN SQLSTATE '22023' THEN
        RAISE NOTICE 'Expected result: terminal-state transition rejected.';
END;
$$;

